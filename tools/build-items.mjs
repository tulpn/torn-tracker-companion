// Writes src/data/items.js: every tradable item's name and id (CMP-201).
//
// Torn's trade page names items ("Xanax x3") but shows no id, and the site's prices are by
// id. Rather than ask the API on every trade, the script carries the table; it is public
// game data. Run it when Torn adds items:
//
//   TORN_API_KEY=<a public key> node tools/build-items.mjs
//
// One call to GET https://api.torn.com/v2/torn/items (openapi.json: /torn/items,
// TornItemsResponse; the key goes in the Authorization header as "ApiKey <key>"). The key
// comes only from the environment and is never written anywhere.

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUT = join(ROOT, 'src', 'data', 'items.js');
const URL = 'https://api.torn.com/v2/torn/items';

/**
 * The tradable items of a TornItemsResponse as [name, id] pairs, sorted by name.
 * Anything that does not look like an item is left out, and a name used twice is
 * dropped, because the trade page could not tell the two apart.
 */
export function tableFrom(response) {
  if (!Array.isArray(response?.items)) throw new Error('not a TornItemsResponse: no items array');
  const byName = new Map();
  const twice = new Set();
  for (const item of response.items) {
    if (!Number.isInteger(item?.id) || item.id <= 0 || typeof item.name !== 'string') continue;
    if (item.is_tradable !== true) continue;
    const name = item.name.trim();
    if (!name || name.length > 100) continue;
    if (byName.has(name)) twice.add(name);
    byName.set(name, item.id);
  }
  for (const name of twice) byName.delete(name);
  return [...byName].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

export function moduleFrom(pairs, date) {
  const rows = pairs.map(([name, id]) => `  [${JSON.stringify(name)}, ${id}],`).join('\n');
  return `// Generated by tools/build-items.mjs on ${date} from GET /v2/torn/items. Do not edit.
// Tradable items by the name Torn's pages show (CMP-201).

export const ITEM_IDS = new Map([
${rows}
]);
`;
}

async function main() {
  const key = process.env.TORN_API_KEY;
  if (!key) {
    console.error('Set TORN_API_KEY (a public key is enough) and run again.');
    process.exit(1);
  }
  const response = await fetch(URL, { headers: { Authorization: `ApiKey ${key}`, Accept: 'application/json' } });
  const data = await response.json();
  if (!response.ok || data?.error) {
    console.error('Torn API refused:', response.status, data?.error?.error ?? '');
    process.exit(1);
  }
  const pairs = tableFrom(data);
  await writeFile(OUT, moduleFrom(pairs, new Date().toISOString().slice(0, 10)));
  console.log(`wrote ${pairs.length} items to ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
