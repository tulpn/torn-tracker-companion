// Writes src/data/icon.js (the userscript's @icon) and src/data/brand.js (the mark drawn by
// src/core/brand.js) from the torn-tracker brand files (hq BRAND-050). Two files,
// because only the mark needs the drawing: the bundle imports brand.js alone.
//
// The sources are copies of the brand files in assets/brand/ (favicon-48.png and
// favicon.svg, from the suite's brand set). The script carries them, so the manager and
// the page make no request for an icon. Run this when the brand files change:
//
//   node tools/build-brand.mjs
//
// The SVG is read into plain values, each checked, and drawn later with createElementNS:
// no markup from the file ever reaches the page.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUT = join(ROOT, 'src', 'data', 'brand.js');
export const ICON_OUT = join(ROOT, 'src', 'data', 'icon.js');
export const PNG = join(ROOT, 'assets', 'brand', 'favicon-48.png');
export const SVG = join(ROOT, 'assets', 'brand', 'favicon.svg');

const NUM = String.raw`-?\d+(?:\.\d+)?`;
const HEX = /^#[0-9a-f]{6}$/i;
const PATH = /^[MLZ\d\s.-]{1,2000}$/;
const PNG_MAGIC = '89504e470d0a1a0a';

/** The mark's tile and raven from favicon.svg, as checked plain values. */
export function markFrom(svg) {
  const attr = (tag, name) => {
    const m = new RegExp(String.raw`<${tag}\b[^>]*\s${name}="([^"]*)"`).exec(svg);
    if (!m) throw new Error(`favicon.svg: no ${tag} ${name}`);
    return m[1];
  };
  const viewBox = attr('svg', 'viewBox');
  if (!new RegExp(`^${NUM}( ${NUM}){3}$`).test(viewBox)) throw new Error(`bad viewBox: ${viewBox}`);
  const tile = {};
  for (const name of ['x', 'y', 'width', 'height', 'rx']) {
    const value = attr('rect', name);
    if (!new RegExp(`^${NUM}$`).test(value)) throw new Error(`bad rect ${name}: ${value}`);
    tile[name] = value;
  }
  tile.fill = attr('rect', 'fill');
  const raven = { fill: attr('path', 'fill'), d: attr('path', 'd') };
  if (!HEX.test(tile.fill) || !HEX.test(raven.fill)) throw new Error('fills must be #rrggbb');
  if (!PATH.test(raven.d)) throw new Error('path data has more than M, L and Z');
  return { viewBox, tile, raven };
}

/** favicon-48.png as a data: URI, after checking it is a PNG. */
export function iconFrom(png) {
  if (png.subarray(0, 8).toString('hex') !== PNG_MAGIC) throw new Error('favicon-48.png is not a PNG');
  return `data:image/png;base64,${png.toString('base64')}`;
}

const NOTE = `// Generated by tools/build-brand.mjs from assets/brand/. Do not edit: replace the brand
// files and run the tool again (hq BRAND-050).
`;

export function iconModule(icon) {
  return `${NOTE}
/** favicon-48.png, the userscript's @icon. Only tools/header.mjs imports it. */
export const ICON_48 = ${JSON.stringify(icon)};
`;
}

export function markModule(mark) {
  const obj = (o) => `Object.freeze({ ${Object.entries(o).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ')} })`;
  return `${NOTE}
/** favicon.svg: the lavender raven on its rounded ink tile, drawn by src/core/brand.js. */
export const MARK = Object.freeze({
  viewBox: ${JSON.stringify(mark.viewBox)},
  tile: ${obj(mark.tile)},
  raven: ${obj(mark.raven)},
});
`;
}

/** { icon, mark }: the text of src/data/icon.js and src/data/brand.js. */
export async function generate() {
  const [png, svg] = await Promise.all([readFile(PNG), readFile(SVG, 'utf8')]);
  return { icon: iconModule(iconFrom(png)), mark: markModule(markFrom(svg)) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { icon, mark } = await generate();
  await writeFile(ICON_OUT, icon);
  await writeFile(OUT, mark);
  console.log(`wrote ${ICON_OUT} and ${OUT}`);
}
