// Writes src/data/tokens.js: the suite's design tokens (hq WP-UI-8, UI-001).
//
// The website's design/tokens.css is the one source of every colour, radius, font and
// motion value; the site exports it as design/tokens.json for the companion and the
// status site. The script carries a copy, so it makes no request for it. Run this when
// the site's tokens change:
//
//   node tools/build-tokens.mjs <path to the site's design/tokens.json>
//
// Every name and value is checked before it is written: a value goes into a stylesheet,
// so anything that could close a declaration or a rule is refused.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUT = join(ROOT, 'src', 'data', 'tokens.js');

const PARTS = ['dark', 'light', 'static'];
const NAME = /^[a-z][a-z0-9-]{0,40}$/;
const HEX = /^#[0-9a-f]{6}$/;
/** Static values: lengths, durations, font stacks, shadows, easing. No ; { } < > \ or url(. */
const STATIC = /^[\w\s.,%#"()/+-]{1,200}$/;

/** The checked tokens of a tokens.json, as { dark, light, static } of name → value. */
export function tokensFrom(json) {
  if (json?.format !== 1) throw new Error('not a tokens.json of format 1');
  const out = {};
  for (const part of PARTS) {
    const given = json[part];
    if (!given || typeof given !== 'object' || Array.isArray(given)) throw new Error(`no "${part}" object`);
    out[part] = {};
    for (const [name, value] of Object.entries(given).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      if (!NAME.test(name)) throw new Error(`bad token name: ${name}`);
      const ok = typeof value === 'string'
        && (part === 'static' ? STATIC.test(value) && !/url\(/i.test(value) : HEX.test(value));
      if (!ok) throw new Error(`bad value for ${part}.${name}: ${JSON.stringify(value)}`);
      out[part][name] = value;
    }
  }
  const dark = Object.keys(out.dark).join();
  if (dark !== Object.keys(out.light).join()) throw new Error('dark and light name different tokens');
  if (!out.dark.primary || !out.dark.background) throw new Error('no primary or background');
  return out;
}

export function moduleFrom(tokens, date) {
  const block = (values) => Object.entries(values)
    .map(([name, value]) => `    ${JSON.stringify(name)}: ${JSON.stringify(value)},`).join('\n');
  return `// Generated by tools/build-tokens.mjs on ${date} from the website's design/tokens.json.
// Do not edit: change the site's design/tokens.css and run the tool again (UI-001).

export const TOKENS = Object.freeze({
${PARTS.map((part) => `  ${part}: Object.freeze({\n${block(tokens[part])}\n  }),`).join('\n')}
});
`;
}

async function main() {
  const from = process.argv[2];
  if (!from) {
    console.error('Usage: node tools/build-tokens.mjs <path to the site\'s design/tokens.json>');
    process.exit(2);
  }
  const tokens = tokensFrom(JSON.parse(await readFile(from, 'utf8')));
  await writeFile(OUT, moduleFrom(tokens, new Date().toISOString().slice(0, 10)), 'utf8');
  console.log(`wrote ${OUT}: ${Object.keys(tokens.dark).length} colours per theme, ${Object.keys(tokens.static).length} static values`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
