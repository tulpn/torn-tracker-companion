/*
 * {{SCRIPT_NAME}}
 *
 * Skeleton conventions (see the torn-script skill):
 *  - No network requests at runtime, no API key. Static data is embedded between the
 *    @@DATA_START / @@DATA_END markers by build-data.ps1.
 *  - Works in Tampermonkey and Torn PDA: @grant none, no GM_* functions.
 *  - Settings persist in Torn PDA's PDA_storage when present, otherwise localStorage, loaded once.
 *  - Decoration is attribute/class-only via CSS; never insert nodes into Torn's own markup.
 *  - No innerHTML. Everything read from storage is validated field by field.
 */

(function () {
  'use strict';

  // ---------------------------------------------------------------- defaults
  // Users change these in the settings panel; saved settings override them.
  const CONFIG = {
    enabled: true,
    showBadge: true,
    debug: false, // not exposed in the panel
  };

  // ---------------------------------------------------------------- data
  // Generated by build-data.ps1. Keep the markers; everything between them is replaced.
  // @@DATA_START
  const DATA_GENERATED = '';
  const DATA = {};
  // @@DATA_END

  const PREFIX = '{{PREFIX}}';            // css class / id / storage prefix, e.g. "tmsh"
  const TAG = '[{{SCRIPT_SLUG}}]';
  const STORE_KEY = `${PREFIX}_settings`;

  const log = (...a) => CONFIG.debug && console.log(TAG, ...a);

  // ---------------------------------------------------------------- storage
  const storage = (() => {
    const pda = typeof PDA_storage !== 'undefined' && PDA_storage && typeof PDA_storage.get === 'function'
      ? PDA_storage : null;
    return {
      backend: pda ? 'PDA_storage' : 'localStorage',
      async load() {
        try {
          if (pda) return await pda.get(STORE_KEY, null);
          const raw = localStorage.getItem(STORE_KEY);
          return raw ? JSON.parse(raw) : null;
        } catch (err) { console.warn(TAG, 'could not load settings', err); return null; }
      },
      async save(obj) {
        try {
          if (pda) await pda.set(STORE_KEY, obj);
          else localStorage.setItem(STORE_KEY, JSON.stringify(obj));
          return true;
        } catch (err) { console.warn(TAG, 'could not save settings', err && err.code, err); return false; }
      },
      async clear() {
        try { if (pda) await pda.delete(STORE_KEY); else localStorage.removeItem(STORE_KEY); }
        catch (err) { console.warn(TAG, 'could not clear settings', err); }
      },
    };
  })();

  // ---------------------------------------------------------------- settings
  // Only keys present in CONFIG survive, and only with the same type as the default.
  const PANEL_KEYS = Object.keys(CONFIG).filter((k) => k !== 'debug');

  function normalizeSettings(raw) {
    const s = raw && typeof raw === 'object' ? raw : {};
    const out = {};
    for (const k of PANEL_KEYS) {
      out[k] = typeof s[k] === typeof CONFIG[k] ? s[k] : CONFIG[k];
    }
    return out;
  }

  let S = normalizeSettings(null);
  let REV = 0; // bump to force every element to be re-evaluated

  // ---------------------------------------------------------------- styles
  const style = document.createElement('style');
  style.textContent = `
    .${PREFIX}-hit { outline: 2px solid #2ecc71 !important; outline-offset: -2px; border-radius: 4px; }
    #${PREFIX}-fab {
      position: fixed; right: 12px; bottom: 84px; z-index: 99998;
      width: 38px; height: 38px; border-radius: 50%;
      background: #222; color: #fff; border: 1px solid #555;
      box-shadow: 0 2px 8px rgba(0,0,0,.4); cursor: pointer;
      display: flex; align-items: center; justify-content: center; font-size: 18px; line-height: 1;
    }
    #${PREFIX}-fab .${PREFIX}-count {
      position: absolute; top: -6px; right: -6px; min-width: 18px; height: 18px; padding: 0 5px;
      border-radius: 9px; background: #2ecc71; color: #000; font: 700 11px/18px sans-serif; text-align: center;
    }
    #${PREFIX}-fab .${PREFIX}-count[hidden] { display: none; }
    #${PREFIX}-panel {
      position: fixed; right: 12px; bottom: 130px; z-index: 99999;
      width: min(370px, calc(100vw - 24px)); max-height: min(80vh, 620px); overflow: auto;
      background: #1e1e1e; color: #eee; border: 1px solid #555; border-radius: 8px; padding: 12px;
      font: 13px/1.4 sans-serif; box-shadow: 0 4px 16px rgba(0,0,0,.5); box-sizing: border-box;
    }
    #${PREFIX}-panel[hidden] { display: none; }
    #${PREFIX}-panel h3 { margin: 0 0 8px; font-size: 14px; }
    #${PREFIX}-panel label.${PREFIX}-check { display: block; margin: 4px 0; }
    #${PREFIX}-panel input[type=checkbox] { margin-right: 6px; }
    #${PREFIX}-panel button {
      background: #333; color: #eee; border: 1px solid #666; border-radius: 4px;
      padding: 4px 9px; cursor: pointer; font: inherit;
    }
    #${PREFIX}-panel button.${PREFIX}-primary { background: #2ecc71; color: #000; border-color: #2ecc71; font-weight: 700; }
    #${PREFIX}-panel .${PREFIX}-row { display: flex; gap: 6px; flex-wrap: wrap; align-items: center; margin-top: 10px; }
    #${PREFIX}-panel .${PREFIX}-muted { color: #999; font-size: 11px; margin-top: 10px; }
    #${PREFIX}-panel .${PREFIX}-status { color: #e74c3c; font-size: 12px; margin-top: 6px; min-height: 1em; }
  `;
  document.head.appendChild(style);

  // ---------------------------------------------------------------- helpers
  const fmt = (n) => '$' + Math.round(n).toLocaleString('en-US');
  const trimZeros = (s) => (s.includes('.') ? s.replace(/\.?0+$/, '') : s);
  function short(n) {
    const a = Math.abs(n);
    if (a >= 1e9) return trimZeros((n / 1e9).toFixed(2)) + 'b';
    if (a >= 1e6) return trimZeros((n / 1e6).toFixed(2)) + 'm';
    if (a >= 1e3) return trimZeros((n / 1e3).toFixed(1)) + 'k';
    return String(Math.round(n));
  }

  // Tiny DOM builder so the panel is built without innerHTML. Text children are always text nodes.
  function el(tag, attrs, ...children) {
    const node = document.createElement(tag);
    for (const [k, v] of Object.entries(attrs || {})) {
      if (v == null || v === false) continue;
      if (k === 'checked' || k === 'selected' || k === 'hidden') node[k] = v;
      else if (k === 'value') node.value = String(v);
      else node.setAttribute(k, v === true ? '' : String(v));
    }
    for (const c of children) {
      node.append(typeof c === 'string' || typeof c === 'number' ? document.createTextNode(String(c)) : c);
    }
    return node;
  }

  // UI chrome we must never decorate: dropdowns, buttons, our own panel.
  function isChrome(node) {
    return !!node.closest(`[role="listbox"], [role="option"], button, [class*="dropdown"], [class*="Dropdown"], #${PREFIX}-panel`);
  }

  // ---------------------------------------------------------------- page logic (EDIT ME)
  // Find the elements this script cares about. Prefer stable hooks (item image URLs, data-*
  // attributes, aria roles) over Torn's hashed class names.
  function findTargets() {
    return document.querySelectorAll('img[src*="/images/items/"]');
  }

  // Return a stable key for a target so unchanged elements are skipped on re-scan.
  function signatureFor(node) {
    return `${node.getAttribute('src')}:${REV}`;
  }

  // Decide and decorate. Only touch classes, data-* attributes, CSS custom properties and title.
  function decorate(node) {
    node.classList.remove(`${PREFIX}-hit`);
    if (!S.enabled) return false;
    const hit = false; // TODO: real condition using DATA
    if (hit) node.classList.add(`${PREFIX}-hit`);
    return hit;
  }

  // ---------------------------------------------------------------- scan
  function scan() {
    let hits = 0;
    for (const node of findTargets()) {
      if (isChrome(node)) continue;
      const sig = signatureFor(node);
      if (node.dataset[`${PREFIX}Sig`] === sig) {
        if (node.classList.contains(`${PREFIX}-hit`)) hits++;
        continue;
      }
      node.dataset[`${PREFIX}Sig`] = sig;
      if (decorate(node)) hits++;
    }
    updateBadge(hits);
  }

  function rescan() {
    REV++;
    scan();
  }

  function updateBadge(n) {
    const badge = document.querySelector(`#${PREFIX}-fab .${PREFIX}-count`);
    if (!badge) return;
    badge.textContent = String(n);
    badge.hidden = !(S.showBadge && n > 0);
  }

  // ---------------------------------------------------------------- settings UI
  let panel = null;

  const LABELS = {
    enabled: 'Enabled',
    showBadge: 'Show count badge on the gear button',
  };

  function buildUI() {
    const fab = el('button', { id: `${PREFIX}-fab`, type: 'button', title: '{{SCRIPT_NAME}} - settings' },
      '⚙',
      el('span', { class: `${PREFIX}-count`, hidden: true }, '0'),
    );
    panel = el('div', { id: `${PREFIX}-panel`, hidden: true });
    document.body.append(fab, panel);

    fab.addEventListener('click', () => {
      panel.hidden = !panel.hidden;
      if (!panel.hidden) renderPanel();
    });
    panel.addEventListener('click', onPanelClick);
  }

  function renderPanel(status) {
    panel.replaceChildren(
      el('h3', null, '{{SCRIPT_NAME}}'),
      ...PANEL_KEYS.filter((k) => typeof CONFIG[k] === 'boolean').map((k) =>
        el('label', { class: `${PREFIX}-check` },
          el('input', { type: 'checkbox', id: `${PREFIX}-${k}`, checked: S[k] }),
          LABELS[k] || k,
        ),
      ),
      el('div', { class: `${PREFIX}-row` },
        el('button', { type: 'button', class: `${PREFIX}-primary`, 'data-act': 'save' }, 'Save'),
        el('button', { type: 'button', 'data-act': 'reset' }, 'Reset to defaults'),
        el('button', { type: 'button', 'data-act': 'close' }, 'Close'),
      ),
      el('div', { class: `${PREFIX}-status` }, status || ''),
      el('div', { class: `${PREFIX}-muted` },
        DATA_GENERATED ? `Data generated ${DATA_GENERATED}. ` : '',
        `Settings are stored only on this device (${storage.backend}).`,
      ),
    );
  }

  function syncFromPanel() {
    for (const k of PANEL_KEYS) {
      if (typeof CONFIG[k] !== 'boolean') continue;
      const input = panel.querySelector(`#${PREFIX}-${k}`);
      if (input) S[k] = input.checked;
    }
  }

  async function onPanelClick(e) {
    const btn = e.target.closest('button[data-act]');
    if (!btn) return;
    const act = btn.dataset.act;
    if (act === 'save') {
      syncFromPanel();
      S = normalizeSettings(S);
      const ok = await storage.save(S);
      rescan();
      if (ok) panel.hidden = true;
      else renderPanel('Could not save settings (storage full or unavailable).');
    } else if (act === 'reset') {
      await storage.clear();
      S = normalizeSettings(null);
      rescan();
      renderPanel();
    } else if (act === 'close') {
      panel.hidden = true;
    }
  }

  // ---------------------------------------------------------------- boot
  async function boot() {
    S = normalizeSettings(await storage.load());
    log('settings', S, 'via', storage.backend);

    buildUI();
    scan();

    let timer = null;
    const scheduleScan = (mutations) => {
      if (mutations && mutations.every((m) => panel.contains(m.target))) return; // our own panel
      clearTimeout(timer);
      timer = setTimeout(scan, 150);
    };
    new MutationObserver(scheduleScan).observe(document.body, { childList: true, subtree: true, characterData: true });
    window.addEventListener('hashchange', () => scheduleScan());
  }

  boot().catch((err) => console.error(TAG, 'failed to start', err));
})();
